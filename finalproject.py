import yfinance as yf
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# 15 Energy Stocks
stocks = {
    "XOM": "Exxon Mobil Corp.",
    "CVX": "Chevron Corp.",
    "COP": "ConocoPhillips",
    "EOG": "EOG Resources Inc.",
    "OXY": "Occidental Petroleum Corp.",
    "DVN": "Devon Energy Corp.",
    "FANG": "Diamondback Energy Inc.",
    "EQT": "EQT Corp.",
    "MPC": "Marathon Petroleum Corp.",
    "VLO": "Valero Energy Corp.",
    "PSX": "Phillips 66",
    "WMB": "Williams Companies Inc.",
    "KMI": "Kinder Morgan Inc.",
    "SLB": "SLB",
    "HAL": "Halliburton Co."
}

tickers = list(stocks.keys())

# Return dates
start_date = "2025-05-15"
end_date = "2026-11-18"

# Download historical price data from Yahoo Finance
raw_data = yf.download(
    tickers,
    start=start_date,
    end=end_date,
    auto_adjust=False,
    progress=False
)

# Extract Adjusted Close prices in exact ticker order and drop any missing rows
adj_close = raw_data["Adj Close"][tickers].dropna()

# Compute simple daily returns: r_t = (P_t - P_{t-1}) / P_{t-1}
returns_df = adj_close.pct_change().dropna()
x = returns_df.to_numpy()
T, N = x.shape

# Verify project constraints (10-20 stocks, 300-400 daily return observations)
assert 10 <= N <= 20, f"Expected 10-20 stocks, got {N}."
assert 300 <= T <= 400, f"Expected 300-400 return days, got {T}. Adjust start_date/end_date."
assert not np.isnan(x).any(), "NaN values detected in return matrix!"

# Print summary table for Report Item #2
summary_table = pd.DataFrame({
    "Ticker": tickers,
    "Company Name": [stocks[t] for t in tickers],
    "Mean Daily Return (%)": (returns_df.mean() * 100).round(4),
    "Daily Volatility (%)": (returns_df.std(ddof=1) * 100).round(4)
})

print("=== DATA SUMMARY FOR REPORT ITEM #2 ===")
print(f"Data Source          : Yahoo Finance (Adjusted Close)")
print(f"Price Series Dates   : {adj_close.index[0].strftime('%Y-%m-%d')} to {adj_close.index[-1].strftime('%Y-%m-%d')} ({len(adj_close)} trading days)")
print(f"Daily Return Dates   : {returns_df.index[0].strftime('%Y-%m-%d')} to {returns_df.index[-1].strftime('%Y-%m-%d')} (T = {T} return days)")
print(f"Number of Stocks (N) : {N}\n")
display(summary_table)

# 1. Standardize the daily returns (zero mean, 1 var): Z = (x - mu) / sigma
mean_returns = np.mean(x, axis=0)
std_returns = np.std(x, axis=0, ddof=1)
Z = (x - mean_returns) / std_returns

# Covariance matrix
cov_matrix = (Z.T @ Z) / (T - 1)
assert np.allclose(cov_matrix, np.cov(Z, rowvar=False)), "Standardized covariance mismatch!"
cov_df = pd.DataFrame(cov_matrix, index=tickers, columns=tickers)

# 3. Compute eigenvalues and eigenvectors of the standardized covariance matrix
eigenvalues, eigenvectors = np.linalg.eigh(cov_matrix)

# Sort eigenvalues (and corresponding eigenvectors) in descending order
sorted_indices = np.argsort(eigenvalues)[::-1]
eigenvalues = eigenvalues[sorted_indices]
eigenvectors = eigenvectors[:, sorted_indices]

# Standardize eigenvector signs (largest-magnitude loading is positive)
for k in range(3):
    max_abs_idx = np.argmax(np.abs(eigenvectors[:, k]))
    if eigenvectors[max_abs_idx, k] < 0:
        eigenvectors[:, k] *= -1

# 4. Extract First Three Principal Components
# (a) Eigenvector loadings (weights across the N standardized stocks)
pc_loadings = eigenvectors[:, :3]
pc_loadings_df = pd.DataFrame(
    pc_loadings,
    index=tickers,
    columns=["PC1", "PC2", "PC3"]
)

# (b) Principal Component scores (daily projected standardized series, T x 3)
pc_scores = Z @ pc_loadings
pc_scores_df = pd.DataFrame(
    pc_scores,
    index=returns_df.index,
    columns=["PC1", "PC2", "PC3"]
)

# 5. Explained Variance Calculations
total_variance = np.sum(eigenvalues)  # Equals N = 15 for standardized data
explained_var_ratio = eigenvalues / total_variance
cumulative_var_ratio = np.cumsum(explained_var_ratio)

variance_df = pd.DataFrame({
    "Principal Component": [f"PC{i}" for i in range(1, 4)],
    "Eigenvalue": eigenvalues[:3],
    "Explained Variance (%)": (explained_var_ratio[:3] * 100).round(2),
    "Cumulative Variance (%)": (cumulative_var_ratio[:3] * 100).round(2)
})


print("=== STANDARDIZED COVARIANCE MATRIX (N x N) ===")
display(cov_df.round(4))

print("\n=== FIRST THREE PRINCIPAL COMPONENTS (LOADINGS) ===")
display(pc_loadings_df.round(4))

print("\n=== EXPLAINED VARIANCE ===")
display(variance_df)
print(f"Total variance explained by the first 3 components: {cumulative_var_ratio[2] * 100:.2f}%")

